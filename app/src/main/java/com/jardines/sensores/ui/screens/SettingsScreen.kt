                            text = "Sistema de Monitoreo Agrícola y Jardinería Inteligente con control de humedad en tiempo real.",
                            fontSize = 11.sp,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }
